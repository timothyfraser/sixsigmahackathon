import {test,expect} from '@playwright/test'
// Deliberately different from every network, to catch implicit browser timezone use.
test.use({timezoneId:'Asia/Tokyo'})
test.beforeEach(async({page})=>{await page.clock.setFixedTime(new Date('2026-10-16T16:00:00Z'));await page.goto('/')})
const startRent=async page=>page.getByRole('button',{name:'Rent a Bike',exact:true}).click()
const setDeparture=async(page,value)=>{await page.getByRole('button',{name:'Leave later',exact:true}).click();await page.getByLabel('Departure date and time',{exact:true}).fill(value)}
async function chooseAvailable(page,action){
 const cards=page.locator('.station-list .station-card')
 for(let i=0;i<await cards.count();i++){const card=cards.nth(i);const b=card.locator('.counts span').nth(1).locator('b');if(Number(await b.textContent())>0){await card.click();await page.getByRole('button',{name:action,exact:true}).click();return}}
 throw new Error('No available fixture station')
}
test('leave later uses network arrival times, forecasts, reordering, and preserves selection',async({page})=>{
 await startRent(page)
 await expect(page.getByRole('button',{name:'Leave now',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(page.getByLabel('Departure date and time',{exact:true})).toHaveCount(0)
 await page.getByTestId('card-jersey-demo-2').click()
 await setDeparture(page,'2026-10-16T17:00')
 await expect(page.locator('.time-zone')).toContainText('America/New_York')
 const card=page.getByTestId('card-jersey-demo-2')
 await expect(card.locator('.counts')).toHaveAttribute('data-target-time','2026-10-16T21:06:00.000Z')
 await expect(card).toContainText('5:06 PM EDT')
 await expect(card).toHaveAttribute('aria-pressed','true')
 await expect(card.locator('.counts span').first()).toContainText('4 bikes now')
 await expect(page.locator('.map-legend')).toContainText('Predicted bikes')
 await expect(page.locator('.map-legend')).toContainText('each walk')
 const expected=await card.locator('.counts span').nth(1).locator('b').textContent()
 await expect(page.locator('[data-station="jersey-demo-2"]')).toHaveText(expected)
 const firstOrder=await page.locator('.station-list .station-card').evaluateAll(cards=>cards.map(c=>c.dataset.testid))
 await page.getByLabel('Departure date and time',{exact:true}).fill('2026-10-16T17:20')
 const secondOrder=await page.locator('.station-list .station-card').evaluateAll(cards=>cards.map(c=>c.dataset.testid))
 expect(firstOrder).not.toEqual(secondOrder)
 await expect(page.getByTestId('card-jersey-demo-2')).toHaveAttribute('aria-pressed','true')
 await expect(page.locator('.marker-count')).toHaveCount(8)
 await page.getByRole('button',{name:'Leave now',exact:true}).click()
 await expect(page.locator('.map-legend')).toContainText('Available bikes')
 await expect(page.locator('[data-station="jersey-demo-2"]')).toHaveText('4')
 await page.screenshot({path:'test-results/time-desktop.png',fullPage:true})
})
test('future dates and network switch use local timezone even with a Tokyo browser',async({page})=>{
 await startRent(page);await setDeparture(page,'2026-10-17T08:30')
 await expect(page.getByTestId('card-jersey-demo-2').locator('.counts')).toHaveAttribute('data-target-time','2026-10-17T12:36:00.000Z')
 await page.getByLabel('Supported network').selectOption('milwaukee')
 await expect(page.getByRole('button',{name:'Leave now',exact:true})).toHaveAttribute('aria-pressed','true')
 await setDeparture(page,'2026-10-17T08:30')
 await expect(page.locator('.time-zone')).toContainText('America/Chicago')
 await expect(page.getByTestId('card-milwaukee-demo-2').locator('.counts')).toHaveAttribute('data-target-time','2026-10-17T13:36:00.000Z')
 await page.getByLabel('Supported network').selectOption('tampa');await setDeparture(page,'2026-10-17T08:30')
 await expect(page.getByTestId('card-tampa-demo-2').locator('.counts')).toHaveAttribute('data-target-time','2026-10-17T12:36:00.000Z')
})
test('invalid, past, unsupported and daylight-saving times are explicit and block continuation',async({page})=>{
 await startRent(page);await setDeparture(page,'2026-10-16T08:00')
 await expect(page.locator('.time-selector')).toContainText('Choose a time at or after')
 await expect(page.getByRole('button',{name:'Choose this pickup station'})).toBeDisabled()
 await page.getByLabel('Departure date and time',{exact:true}).fill('')
 await expect(page.locator('.time-selector')).toContainText('Choose a complete date and time')
 await page.getByLabel('Departure date and time',{exact:true}).fill('2027-03-14T02:30')
 await expect(page.locator('.time-selector')).toContainText('does not exist')
 await page.getByLabel('Departure date and time',{exact:true}).fill('2026-11-01T01:30')
 await expect(page.getByLabel('Repeated clock time')).toBeVisible()
 await expect(page.getByRole('button',{name:'Choose this pickup station'})).toBeDisabled()
 await page.getByLabel('Repeated clock time').selectOption('earlier')
 await expect(page.getByTestId('card-jersey-demo-2').locator('.counts')).toHaveAttribute('data-target-time','2026-11-01T05:36:00.000Z')
 await page.getByLabel('Repeated clock time').selectOption('later')
 await expect(page.getByTestId('card-jersey-demo-2').locator('.counts')).toHaveAttribute('data-target-time','2026-11-01T06:36:00.000Z')
 await page.getByLabel('Departure date and time',{exact:true}).fill('2028-01-01T12:00')
 await expect(page.locator('.time-selector')).toContainText('365 days')
 await expect(page.locator('.marker-count').first()).toHaveText('—')
})
test('direct return has its own exact return time and future dock markers',async({page})=>{
 await page.getByRole('button',{name:'Return a Bike',exact:true}).click()
 await expect(page.getByRole('button',{name:'Return now',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Return later',exact:true}).click()
 await page.getByLabel('Expected return date and time',{exact:true}).fill('2026-10-16T17:00')
 await expect(page.locator('.map-legend')).toContainText('Predicted free docking spaces')
 for(const card of await page.locator('.station-list .station-card').all())await expect(card.locator('.counts')).toHaveAttribute('data-target-time','2026-10-16T21:00:00.000Z')
 await chooseAvailable(page,'Choose this return dock')
 await expect(page.getByRole('heading',{name:'Your return is planned.'})).toBeVisible()
 await expect(page.locator('.planned-times')).toContainText('5:00 PM EDT')
 await expect(page.locator('.trip-itinerary')).not.toContainText('PICK UP YOUR BIKE')
 await page.getByRole('button',{name:'Change return dock'}).click()
 await expect(page.getByLabel('Expected return date and time',{exact:true})).toHaveValue('2026-10-16T17:00')
})
test('full journey adds walk then per-dock ride, supports adjusted return and restart',async({page})=>{
 await startRent(page);await setDeparture(page,'2026-10-16T17:00')
 const pickup=page.getByTestId('card-jersey-demo-2')
 await page.locator('[data-station="jersey-demo-2"]').click();await pickup.click();await page.getByRole('button',{name:'Choose this pickup station'}).click()
 await page.getByRole('button',{name:'Find return docks'}).click()
 await page.locator('[data-station="jersey-demo-2"]').click()
 const dock=page.getByTestId('card-jersey-demo-2')
 await expect(dock.locator('.counts')).toHaveAttribute('data-target-time','2026-10-16T21:15:00.000Z')
 await page.getByRole('button',{name:'Adjust return time',exact:true}).click()
 await page.getByLabel('Expected return date and time',{exact:true}).fill('2026-10-16T17:00')
 await expect(page.locator('.time-selector')).toContainText('after your estimated pickup')
 await page.getByLabel('Expected return date and time',{exact:true}).fill('2026-10-16T18:00')
 await chooseAvailable(page,'Choose this return dock')
 await expect(page.locator('.planned-times')).toContainText('5:06 PM EDT')
 await expect(page.locator('.planned-times')).toContainText('6:00 PM EDT')
 await page.getByRole('button',{name:'Change pickup'}).click()
 await expect(page.getByLabel('Departure date and time',{exact:true})).toHaveValue('2026-10-16T17:00')
 await page.locator('.brand').click();await startRent(page)
 await expect(page.getByRole('button',{name:'Leave now',exact:true})).toHaveAttribute('aria-pressed','true')
})
test('zero forecast requests reselection and replay updates both current and forecast values',async({page})=>{
 await startRent(page);await setDeparture(page,'2026-10-16T17:00')
 let found=false
 for(let minute=0;minute<80&&!found;minute+=5){
   await page.getByLabel('Departure date and time',{exact:true}).fill(`2026-10-16T${String(17+Math.floor(minute/60)).padStart(2,'0')}:${String(minute%60).padStart(2,'0')}`)
   for(const marker of await page.locator('.marker-count').all())if(await marker.textContent()==='0'){await marker.click();found=true;break}
 }
 expect(found).toBe(true)
 await expect(page.locator('.selection-action')).toContainText('Choose another station')
 await expect(page.getByRole('button',{name:'Choose this pickup station'})).toBeDisabled()
 await page.getByRole('button',{name:'Advance 5 minutes'}).click()
 await expect(page.locator('.replay-bar')).toContainText('Snapshot 2 of 3')
 await expect(page.getByTestId('card-jersey-demo-1').locator('.counts span').first()).toContainText('6 bikes now')
})
