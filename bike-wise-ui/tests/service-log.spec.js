import {test,expect} from '@playwright/test'
async function login(page){
 await page.goto('/');await page.getByRole('button',{name:'maintenance login here',exact:true}).click()
 await page.getByLabel('Email address',{exact:true}).fill('maintenance@cornell.edu')
 if(!process.env.MAINTENANCE_TEST_PASSWORD)throw new Error('Set MAINTENANCE_TEST_PASSWORD.')
 await page.getByLabel('Password',{exact:true}).fill(process.env.MAINTENANCE_TEST_PASSWORD)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(page.getByRole('button',{name:'Service log',exact:true})).toBeVisible()
}
test('service log is protected and opens without inventing records',async({page})=>{
 await page.goto('/')
 expect((await page.request.get('/api/maintenance/service-log?city=jersey')).status()).toBe(401)
 expect((await page.request.post('/api/maintenance/service-log?city=jersey',{data:{records:[]}})).status()).toBe(401)
 await login(page);await page.getByRole('button',{name:'Service log',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Service log',exact:true})).toBeVisible()
 await expect(page.getByLabel('Serviced bike ID',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Import service log CSV',{exact:true})).toBeVisible()
})
test('recorded and imported services reset package hours, persist and rerank priorities',async({page})=>{
 test.setTimeout(120000)
 test.skip(process.env.SERVICE_LOG_TEST_ISOLATED!=='true','Run only against an isolated service-log test file; never mutate an operator journal.')
 await login(page)
 const baseline=await(await page.request.get('/api/maintenance/report?city=jersey')).json()
 const bike=baseline.service_due.find(row=>row.current_dock!=='0'),other=baseline.service_due.find(row=>row.BIKEID!==bike.BIKEID)
 const before=baseline.stations.find(row=>row.DOCID===bike.current_dock)
 await page.getByRole('button',{name:'Service log',exact:true}).click()
 await page.getByLabel('Serviced bike ID',{exact:true}).selectOption(bike.BIKEID)
 await page.getByLabel('Service note',{exact:true}).fill('Isolated browser check: completed preventive service')
 await page.getByRole('button',{name:'Record service',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('1 service record saved',{timeout:90000})
 const after=await(await page.request.get('/api/maintenance/report?city=jersey')).json()
 expect(after.service_due.some(row=>row.BIKEID===bike.BIKEID)).toBe(false)
 expect(after.service_status.find(row=>row.BIKEID===bike.BIKEID)).toMatchObject({ride_hours:0,due:false})
 expect(after.stations.find(row=>row.DOCID===bike.current_dock).n_due).toBe(before.n_due-1)
 const entries=await(await page.request.get('/api/maintenance/service-log?city=jersey')).json()
 const repeat=await page.request.post('/api/maintenance/service-log?city=jersey',{data:{records:[{BIKEID:bike.BIKEID,service_time:baseline.reference_time}]}})
 expect((await repeat.json()).added).toBe(0)
 const content=`BIKEID,service_time,note\n${other.BIKEID},${baseline.reference_time},"Isolated CSV import"\n`
 await page.getByLabel('Import service log CSV',{exact:true}).setInputFiles({name:'service-log-check.csv',mimeType:'text/csv',buffer:Buffer.from(content)})
 await expect(page.getByRole('status')).toContainText('1 service record saved',{timeout:90000})
 const invalid=await page.request.post('/api/maintenance/service-log?city=jersey',{data:{records:[{BIKEID:'unknown-bike',service_time:baseline.reference_time}]}})
 expect(invalid.status()).toBe(422)
 await page.reload();await page.getByRole('button',{name:'maintenance login here',exact:true}).click()
 await expect(page.getByRole('button',{name:'Service log',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Service log',exact:true}).click()
 await expect(page.locator('.service-log-panel tbody tr')).toHaveCount(entries.records.length+1)
 await expect(page.locator('.service-log-panel')).toContainText(bike.BIKEID)
 const finalReport=await(await page.request.get('/api/maintenance/report?city=jersey')).json()
 expect(finalReport.service_log_summary.effective).toBe(baseline.service_log_summary.effective+2)
 await page.screenshot({path:'test-results/service-log.png',fullPage:true})
})
