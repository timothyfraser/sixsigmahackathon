test('yellow eligible pickup and return markers can complete a rental without entering the top-five list',async({page})=>{
 await page.setViewportSize({width:1440,height:1000});await page.goto('/')
 await page.getByRole('button',{name:'Rent a Bike',exact:true}).click()
 await page.getByRole('button',{name:'Find pickup docks',exact:true}).click()
 const planner=await page.locator('.planner').boundingBox(),map=await page.locator('.optimizer-map-wrap').boundingBox(),list=await page.locator('.optimizer-options').boundingBox()
 expect(planner.y+planner.height).toBeLessThanOrEqual(map.y)
 expect(map.x).toBeLessThan(list.x)
 expect(map.x).toBeLessThan(60)
 const names=await page.locator('.optimizer-card').evaluateAll(els=>els.map(el=>el.dataset.dock))
 const yellow=page.locator('.optimizer-map-wrap path[data-recommended="false"][aria-label$="other eligible dock"]').first()
 const pickup=await yellow.getAttribute('data-dock')
 expect(names).not.toContain(pickup)
 await yellow.focus();await page.keyboard.press('Enter')
 await expect(page.locator('.journey-selection')).toContainText(pickup)
 await expect(page.locator('.journey-selection')).toContainText('Another eligible dock')
 await expect(page.locator('.optimizer-card')).toHaveCount(5)
 await expect(page.getByRole('button',{name:'Choose this pickup station'})).toBeEnabled()
 const cardName=page.locator('.optimizer-card .card-name').first(),walk=page.locator('.optimizer-card-meta>span').first(),count=page.locator('.optimizer-availability strong').first()
 expect(await cardName.evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThan(await count.evaluate(el=>parseFloat(getComputedStyle(el).fontSize)))
 expect(await walk.evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThan(await count.evaluate(el=>parseFloat(getComputedStyle(el).fontSize)))
 await page.screenshot({path:'test-results/map-left-yellow-pickup.png',fullPage:true})
 await page.getByRole('button',{name:'Choose this pickup station'}).click()
 await page.getByLabel('Optimizer location').selectOption('JC-U07')
 await page.getByRole('button',{name:'Find return docks',exact:true}).click()
 const returnMarker=page.locator('.optimizer-map-wrap path[data-recommended="false"][aria-label$="other eligible dock"]').first()
 const returnName=await returnMarker.getAttribute('data-dock')
 await returnMarker.dispatchEvent('click')
 await expect(page.locator('.optimizer-card')).toHaveCount(5)
 await expect(page.getByRole('button',{name:'Choose this return dock'})).toBeEnabled()
 await page.getByRole('button',{name:'Choose this return dock'}).click()
 const itinerary=page.getByRole('region',{name:'Your itinerary'})
 await expect(itinerary).toBeVisible()
 await expect(itinerary).toContainText(pickup)
 await expect(itinerary).toContainText(returnName)
 await expect(page.getByText('Your demo plan is ready.',{exact:true})).toHaveCount(0)
 const itineraryBounds=await itinerary.boundingBox(),summaryMap=await page.locator('.optimizer-map-wrap').boundingBox()
 expect(itineraryBounds.x).toBeGreaterThan(summaryMap.x)
 await page.screenshot({path:'test-results/itinerary-desktop.png',fullPage:true})
})
