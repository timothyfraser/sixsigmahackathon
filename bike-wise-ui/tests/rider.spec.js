test('Tampa desktop map uses the same tile service and supports rent and replay', async ({page}) => {
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('/')
 await expect(page.getByLabel('Supported network').locator('option')).toHaveText(['Jersey City · mock','Milwaukee · mock','Tampa · mock'])
 await page.getByLabel('Supported network').selectOption('tampa')
 await page.getByRole('button',{name:'Rent a Bike',exact:true}).click()
 await expect(page.locator('img.leaflet-tile').first()).toHaveAttribute('src',/^https:\/\/[abc]\.tile\.openstreetmap\.org\//)
 await expect.poll(()=>page.locator('img.leaflet-tile').evaluateAll(tiles=>tiles.some(tile=>tile.complete&&tile.naturalWidth>0))).toBe(true)
 await expect(page.locator('canvas')).toHaveCount(0)
 await expect(page.locator('[data-station="tampa-demo-1"]')).toHaveText('8')
 await page.getByRole('button',{name:'Advance 5 minutes'}).click()
 await expect(page.locator('[data-station="tampa-demo-1"]')).toHaveText('6')
 await expect(page.locator('.station-list .station-card')).toHaveCount(5)
 await page.getByRole('button',{name:'Choose this pickup station'}).click()
 await expect(page.locator('.saved-station')).toContainText('Riverwalk Plaza')
 await page.getByRole('button',{name:'Find return docks'}).click()
 await expect(page.locator('.map-legend')).toContainText('Predicted free docking spaces')
 await page.getByRole('button',{name:'Choose this return dock'}).click()
 await expect(page.getByRole('heading',{name:"You're ready to ride!"})).toBeVisible()
 expect(errors).toEqual([])
 await page.screenshot({path:'test-results/tampa-desktop.png',fullPage:true})
})
