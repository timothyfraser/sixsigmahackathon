import {test,expect} from '@playwright/test'
test.beforeEach(async({page})=>{await page.clock.setFixedTime(new Date('2026-10-16T16:00:00Z'))})
test('rental journey, selection, replay, back navigation and restart',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/')
 await expect(page.getByRole('heading',{name:'What would you like to do?'})).toBeVisible()
 await expect(page.getByRole('button',{name:'Rent a Bike',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Return a Bike',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Rent a Bike',exact:true}).click()
 await expect(page.locator('.station-card')).toHaveCount(5)
 await expect(page.locator('.marker-count')).toHaveCount(8)
 for(const [id,count] of [['jersey-demo-1','8'],['jersey-demo-2','4'],['jersey-demo-3','12'],['jersey-demo-4','0'],['jersey-demo-5','2']])await expect(page.locator(`[data-station="${id}"]`)).toHaveText(count)
 await page.getByTestId('card-jersey-demo-3').click();await expect(page.locator('[data-station="jersey-demo-3"]')).toHaveClass(/chosen/)
 await page.locator('[data-station="jersey-demo-2"]').click();await expect(page.getByTestId('card-jersey-demo-2')).toHaveAttribute('aria-pressed','true')
 await expect(page.locator('.leaflet-popup-content')).toContainText('Capacity: 15')
 await page.getByRole('button',{name:'Advance 5 minutes'}).click();await expect(page.locator('[data-station="jersey-demo-2"]')).toHaveText('5');await expect(page.getByTestId('card-jersey-demo-2').locator('.counts')).toContainText('5 bikes now')
 // This replay bucket has zero expected bikes: confirmation must block until availability changes.
 await expect(page.getByRole('button',{name:'Choose this pickup station'})).toBeDisabled()
 await expect(page.locator('.selection-action')).toContainText('Choose another station')
 await page.getByRole('button',{name:'Advance 5 minutes'}).click()
 await page.getByRole('button',{name:'Choose this pickup station'}).click();await expect(page.locator('.saved-station')).toContainText('Van Vorst Park')
 await page.getByLabel('Destination',{exact:true}).selectOption('2');await expect(page.locator('.saved-station')).toContainText('Van Vorst Park')
 await page.getByRole('button',{name:'Back',exact:true}).click();await expect(page.getByTestId('card-jersey-demo-2')).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Choose this pickup station'}).click();await expect(page.getByLabel('Destination',{exact:true})).toHaveValue('2')
 await page.getByRole('button',{name:'Find return docks'}).click();await expect(page.locator('.map-legend')).toContainText('Predicted free docking spaces');const expectedDockCount=await page.getByTestId('card-jersey-demo-2').locator('.counts span').nth(1).locator('b').textContent();await expect(page.locator('[data-station="jersey-demo-2"]')).toHaveText(expectedDockCount)
 await page.getByRole('button',{name:'Choose this return dock'}).click();await expect(page.getByRole('heading',{name:"You're ready to ride!"})).toBeVisible();await expect(page.locator('.trip-itinerary')).toContainText('Hamilton Park')
 await expect(page.getByRole('status')).toContainText('DEMO MODE')
 await page.getByRole('button',{name:'Plan another ride'}).click();await expect(page.getByRole('heading',{name:'What would you like to do?'})).toBeVisible();await expect(page.locator('[data-station="jersey-demo-2"]')).toHaveText('4')
 expect(errors).toEqual([])
})
