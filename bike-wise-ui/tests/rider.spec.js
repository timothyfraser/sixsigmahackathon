import {test,expect} from '@playwright/test'

test('rental completes location pickup destination return and summary on one map',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/')
 await expect(page.locator('.optimizer-card')).toHaveCount(0)
 await page.locator('.optimizer-map-wrap .leaflet-container').evaluate(el=>{el.__sameMap=true})
 await page.locator('.home-choice').first().click()
 await expect(page.getByLabel('Optimizer location')).toBeVisible()
 await expect(page.locator('.optimizer-card')).toHaveCount(0)
 await page.getByLabel('Optimizer location').selectOption('JC-U04')
 await page.getByRole('button',{name:'Find pickup docks',exact:true}).click()
 await expect(page.locator('.optimizer-card')).toHaveCount(5)
 await expect(page.getByRole('button',{name:'Choose this pickup station'})).toBeDisabled()
 const pickup=await page.locator('.optimizer-card').nth(1).getAttribute('data-dock')
 await page.locator('.optimizer-card').nth(1).click()
 await page.getByRole('button',{name:'Choose this pickup station'}).click()
 await expect(page.locator('.saved-station')).toContainText(pickup)
 await expect(page.getByRole('heading',{name:'Where are you heading?'})).toBeVisible()
 await page.getByLabel('Optimizer location').selectOption('JC-U08')
 await page.getByRole('button',{name:'Back',exact:true}).click()
 await expect(page.locator('.optimizer-card')).toHaveCount(5)
 await page.locator('.optimizer-card').nth(1).click()
 await page.getByRole('button',{name:'Choose this pickup station'}).click()
 await expect(page.getByLabel('Optimizer location')).toHaveValue('JC-U08')
 await page.getByRole('button',{name:'Find return docks',exact:true}).click()
 await expect(page.locator('.optimizer-card')).toHaveCount(5)
 const dock=await page.locator('.optimizer-card').first().getAttribute('data-dock')
 await page.locator('.optimizer-card').first().click()
 await page.getByRole('button',{name:'Choose this return dock'}).click()
 await expect(page.getByRole('heading',{name:"You're ready to ride!"})).toBeVisible()
 await expect(page.locator('.trip-itinerary')).toContainText(pickup)
 await expect(page.locator('.trip-itinerary')).toContainText(dock)
 expect(await page.locator('.optimizer-map-wrap .leaflet-container').evaluate(el=>el.__sameMap)).toBe(true)
 await page.getByRole('button',{name:'Change return dock'}).click()
 await expect(page.locator('.optimizer-card')).toHaveCount(5)
 await page.locator('.optimizer-card').first().click()
 await page.getByRole('button',{name:'Choose this return dock'}).click()
 await page.getByRole('button',{name:'Plan another ride'}).click()
 await expect(page.getByRole('heading',{name:'What would you like to do?'})).toBeVisible()
 await expect(page.getByLabel('Optimizer location')).toHaveCount(0)
 expect(errors).toEqual([])
})

